#ifndef METEO11CODEC_H
#define METEO11CODEC_H

#include <QString>

#include "core/meteo11/Meteo11Data.h"

// ─────────────────────────────────────────────────────────────────────────────
// Кодирование бюллетеня Метео-11 по протоколу.
//
// Чистые вычисления над числами и строками: ни одной зависимости от QtWidgets,
// ни одного обращения к экрану. Раньше эти функции были приватными
// статическими методами виджета MeasurementResults — то есть правила
// кодирования протокола нельзя было ни использовать, ни проверить, не подняв
// целую страницу интерфейса.
//
// Функции перенесены дословно, формулы и округления не менялись.
// ─────────────────────────────────────────────────────────────────────────────
namespace Meteo11Codec {

/**
 * Стандартное давление МСА на высоте altM (м), мм рт. ст.
 *
 * ПРИМЕЧАНИЕ: на момент выделения модуля эта функция и соседняя
 * standardTempAtAlt в программе не вызываются. Они перенесены как есть,
 * чтобы рефакторинг не менял состав кода; удалять их — отдельное решение.
 */
double standardPressureAtAlt(double altM);

/** Стандартная температура МСА на высоте altM (м), °C */
double standardTempAtAlt(double altM);

/**
 * Кодировать направление ветра в делениях угломера (большие деления, шаг 0-60).
 * degrees — метеорологическое направление 0..360 (откуда дует).
 * Возвращает 00..60 (60 означает «штиль» или отдельно обрабатывается).
 */
int encodeWindDir(int degrees);

/**
 * Кодировать отклонение давления (мм рт.ст.) в поле БББ.
 * Правило: если отклонение отрицательное — прибавляем 500 к первой цифре
 * (или по упрощённому: добавляем 500 ко всему значению при отклонении < 0).
 */
int encodePressureDev(double deltaMmHg);

/**
 * Кодировать отклонение температуры (°C) в поле ТТ (двузначное).
 * Правило: отрицательные — прибавить 50 к первой цифре => первая цифра 5-9.
 */
int encodeTempDev(double deltaCelsius);

/**
 * Сформировать текстовую группу одного слоя для строкового бюллетеня.
 * Ниже 10 км: ППТТННСС (4+6 цифр со знаком «-» между ними).
 * Выше 10 км: ВВ-ТТННСС (2+6 цифр).
 * В данной реализации группа = "HННСС" (с указанием высоты и параметров).
 *
 * Реальный формат строки Метео-11:
 *  ≤10 км: ХХХХ-ТТННСС  (4-значный код высоты + 6-значный ТТННСС)
 *  >10 км: ХХ-ТТННСС   (2-значный код + 6-значный)
 */
QString formatMeteo11Group(int heightCode, const QString &pp, int dir, int speed,
                           int tempDev, bool above10km, bool includePP = true,
                           bool unavailable = false);

/**
 * Построить полную строку бюллетеня Метео-11 из структуры данных.
 * Формат: «Метео 11NNNNN–ДДЧЧМ–BBBB–БББT0T0–02ПП–ТТННСС–...–BтBтBвBв»
 */
QString buildMeteo11String(const Meteo11Data &d);

} // namespace Meteo11Codec

#endif // METEO11CODEC_H
