#pragma once
#include <QVector>

// Один уровень профиля ветра над землёй (AGL), полученный интерполяцией
// по узлам регулярной сетки GRIB (см. Mushroom + пересчёт AMSL->AGL
// через геопотенциальную высоту). Соответствует h_k, U_GR^k, V_GR^k
// из методики.
struct LevelWind {
    double heightAglM = 0.0; // высота над землёй, м
    double vz = 0.0;         // зональная составляющая ветра (U), м/с
    double vm = 0.0;         // меридиональная составляющая ветра (V), м/с
};

// Приземный ветер f_0 на h_0 = 0, измеренный отдельным прибором в тот
// же момент времени, что и профиль (в тестовой программе вводится
// вручную; в конечной системе должен приходить от реального датчика).
struct SurfaceWind {
    double vz = 0.0;
    double vm = 0.0;
};

// Стандартные верхние границы слоёв метеобюллетеня (в метрах),
// см. документ методики: 0-200, 0-400, ..., 0-8000.
inline const QVector<int>& meteo11StandardLayersM()
{
    static const QVector<int> layers = {
        200, 400, 800, 1200, 1600, 2000, 2400, 3000, 4000, 5000, 6000, 8000
    };
    return layers;
}

// Результат расчёта среднего ветра в одном слое 0..Y_l.
struct Meteo11LayerResult {
    int layerTopM = 0;          // верхняя граница слоя Y_l, м
    bool sufficientData = false; // false — краевой случай, для которого
                                  // по методике нужна климатическая база
                                  // данных (шаги 4/7, формула 5), которой
                                  // пока нет; такой слой помечается как
                                  // "недостаточно данных" вместо расчёта
    double vzAvg = 0.0;         // среднее по слою (зональная составляющая)
    double vmAvg = 0.0;         // среднее по слою (меридиональная составляющая)
    double speedMs = 0.0;       // скорость среднего ветра, м/с (формула 6)
    double directionDeg = 0.0;  // дирекционный угол, градусы (формула 6)
};
