#pragma once
#include <QVector>
#include "Meteo11Types.h"

// Реализация методики пересчёта профиля ветра (приземное значение +
// уровни, полученные интерполяцией по GRIB) в осреднённые по
// стандартным слоям (0-200 ... 0-8000 м) значения скорости и
// дирекционного угла среднего ветра — аналог бюллетеня "Метеосредний".
//
// Не зависит ни от Qt Widgets, ни от способа получения входных данных
// (Mushroom/GRIB) — принимает уже готовый профиль LevelWind и
// SurfaceWind. Это сделано намеренно, чтобы модуль можно было
// использовать в другом проекте без UI, просто передав ему данные.
//
// Реализованы:
//   Шаг 1-2 (формулы 1-3) — интерполяция, когда Y_l лежит между двумя
//     доступными уровнями данных (основной, наиболее частый случай).
//   Шаг 5-6 (формула 3 с экстраполяцией по последним двум точкам) —
//     когда Y_l выше самого верхнего уровня данных, но есть хотя бы
//     два уровня для оценки наклона.
// НЕ реализованы (требуют базы климатических данных, которой пока нет
// по решению пользователя — такие слои помечаются sufficientData=false):
//   Шаг 4 (формула 5) — нет уровня данных выше h_m совсем.
//   Шаг 7 (формула 5) — нет уровня данных ниже h_m совсем.
class Meteo11Calculator {
public:
    // profile может быть в любом порядке и содержать дубли по высоте —
    // метод сам сортирует и очищает. Возвращает по одному результату на
    // каждый стандартный слой из meteo11StandardLayersM().
    static QVector<Meteo11LayerResult> compute(const SurfaceWind &surface,
                                                 QVector<LevelWind> profile);

private:
    // Среднее значение параметра (зонального или меридионального) в слое
    // 0..heights[uptoIndex] по формуле (1). heights/values включают
    // приземную точку (0, f0) под индексом 0.
    static double trapezoidAverage(const QVector<double> &heights,
                                    const QVector<double> &values,
                                    int uptoIndex);

    // Линейная интерполяция/экстраполяция среднего к высоте targetH по
    // формуле (3), используя два опорных уровня (h1,avg1) и (h2,avg2).
    static double interpolateAverage(double h1, double avg1,
                                      double h2, double avg2,
                                      double targetH);
};
